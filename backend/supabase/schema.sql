-- BASE DE DATOS - MODULO DE NOTIFICACIONES
-- Supabase / PostgreSQL
-- Esquema final indicado para la integracion TicketU. eventos_procesado

-- ------------------------------- ENTRADAS ---------------------------------
CREATE TABLE IF NOT EXISTS public.entradas_usuario (
    id_entradas_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario TEXT NOT NULL,
    id_evento TEXT NOT NULL,
    correo_comprador TEXT NOT NULL,
    nombre_evento TEXT NOT NULL,
    fecha_evento TIMESTAMPTZ NOT NULL,
    entrada_activa BOOLEAN NOT NULL DEFAULT TRUE,
    estado_evento TEXT NOT NULL DEFAULT 'PROGRAMADO',
    -- created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (id_usuario, id_evento),
    CONSTRAINT check_entradas_usuario_estado_evento
        CHECK (estado_evento IN ('PROGRAMADO', 'CANCELADO', 'FINALIZADO', 'REPROGRAMADO', 'BORRADOR'))
);

-- ---------------------------- NOTIFICACIONES ------------------------------
CREATE TABLE IF NOT EXISTS public.notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario TEXT NOT NULL,
    tipo TEXT NOT NULL,
    mensaje TEXT NOT NULL,
    datos JSONB NOT NULL DEFAULT '{}'::jsonb,
    estado_lectura TEXT NOT NULL DEFAULT 'NO_LEIDA',
    fecha_eliminacion TIMESTAMPTZ,
    canal TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT check_notificacion_tipo
        CHECK (tipo IN (
            'COMPRA', 'RECORDATORIO', 'RECORDATORIO_24H', 'RECORDATORIO_30M',
            'INICIO_EVENTO', 'EVENTO_CAMBIO', 'CAMBIO_EVENTO', 'CANCELACION_EVENTO',
            'RECUPERACION_PASSWORD', 'CREACION_STAFF'
        )),
    CONSTRAINT check_notificacion_estado_lectura
        CHECK (estado_lectura IN ('NO_LEIDA', 'LEIDA', 'ELIMINADA')),
    CONSTRAINT check_notificacion_canal
        CHECK (canal IN ('APP', 'EMAIL'))
);

-- ----------------------- ENVIOS DE NOTIFICACION ---------------------------
CREATE TABLE IF NOT EXISTS public.envios_notificacion (
    id_envio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_notificacion BIGINT NOT NULL
        REFERENCES public.notificacion(id_notificacion) ON DELETE CASCADE,
    estado_envio TEXT NOT NULL,
    intento INTEGER NOT NULL DEFAULT 1,
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT check_envios_estado
        CHECK (estado_envio IN ('PENDIENTE', 'ENVIADO', 'ERROR'))
);

-- ----------------------- EVENTOS UNICOS  --------------------------
CREATE TABLE IF NOT EXISTS public.eventos_procesados (
    clave_evento TEXT PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- -------------------------------- INDICES ----------------------------------
CREATE INDEX IF NOT EXISTS idx_entradas_usuario
    ON public.entradas_usuario(id_usuario);
CREATE INDEX IF NOT EXISTS idx_entradas_evento
    ON public.entradas_usuario(id_evento);
CREATE INDEX IF NOT EXISTS idx_entradas_fecha_evento
    ON public.entradas_usuario(fecha_evento);
CREATE INDEX IF NOT EXISTS idx_notificacion_usuario
    ON public.notificacion(id_usuario);
CREATE INDEX IF NOT EXISTS idx_notificacion_no_leidas
    ON public.notificacion(id_usuario) WHERE estado_lectura = 'NO_LEIDA';
CREATE INDEX IF NOT EXISTS idx_notificacion_app_usuario_fecha
    ON public.notificacion (id_usuario, created_at DESC)
    WHERE canal = 'APP' AND estado_lectura <> 'ELIMINADA' AND fecha_eliminacion IS NULL;
CREATE INDEX IF NOT EXISTS idx_envios_notificacion
    ON public.envios_notificacion(id_notificacion);
